-- Parity fixture schema (REFACTOR_PLAN.md P1-6). SYNTHETIC DATA ONLY (PD-3).
--
-- Only the columns the incremental ETL reads are modelled. Column types and
-- nullability follow the alembic migration
-- Development-Sinarmas/migration-engine/alembic_clean/versions/dev/7661454aa632_add_test_vendor.py
-- where a column appears there. Server defaults are deliberately omitted: the
-- generator supplies every value, so no default can leak a real-looking value.
--
-- [A] Not in that migration, so their shape is assumed:
--   * events_bc.sync_time / links_bc.sync_time  -> timestamptz, nullable
--   * mv_subject_hierarchy                      -> plain table carrying only the
--     five columns eventDetailsQuery reads (a materialized view in production)
--
-- Synthetic marker: every identifier column is CHECK-constrained to the
-- 'SYN-' prefix, so a row copied from Staging or Production cannot be loaded.

CREATE TABLE events_bc (
    unique_id          varchar     NOT NULL CHECK (unique_id LIKE 'SYN-%'),
    client_id          varchar     NOT NULL,
    bl_number          varchar,
    sales_order        varchar     NOT NULL,
    product_id         varchar     NOT NULL,
    product_name       text        NOT NULL,
    plant              varchar,
    production_label   varchar,
    process_date       integer     NOT NULL,
    material_type      varchar     NOT NULL,
    material_code      varchar,
    amount             numeric     NOT NULL,
    unit               varchar     NOT NULL,
    src_path           jsonb,
    sub_data_source    varchar,
    version            varchar(50),
    flag               varchar     NOT NULL,
    material_document  varchar,
    purchase_order     varchar,
    uml_id             varchar(50),
    location_id        varchar     NOT NULL,
    vendor             varchar,
    source             varchar     NOT NULL,
    movement_type      varchar,
    movement_type_text text,
    storage_location   varchar,
    partner_pca        varchar,
    mill_name          text,
    status             varchar(10),
    sync_time          timestamptz
);

CREATE TABLE links_bc (
    id             bigint      PRIMARY KEY,
    event1_id      varchar     NOT NULL CHECK (event1_id LIKE 'SYN-%'),
    event2_id      varchar     NOT NULL CHECK (event2_id LIKE 'SYN-%'),
    role           varchar     NOT NULL,
    qty            numeric     NOT NULL,
    unit           varchar     NOT NULL,
    source         varchar     NOT NULL,
    status         varchar(10),
    event1_version varchar(50),
    event2_version varchar(50),
    sync_time      timestamptz
);

CREATE TABLE subjects (
    subject_id   varchar NOT NULL UNIQUE CHECK (subject_id LIKE 'SYN-%'),
    master_type  varchar NOT NULL,
    subject_type varchar NOT NULL,
    master_id    varchar NOT NULL
);

CREATE TABLE mv_subject_hierarchy (
    start_subject_id varchar NOT NULL CHECK (start_subject_id LIKE 'SYN-%'),
    subject_id       varchar,
    subject_type     varchar,
    master_id        varchar,
    master_type      varchar
);

CREATE TABLE master_mill (
    mill_id varchar NOT NULL CHECK (mill_id LIKE 'SYN-%'),
    uml_id  varchar
);

COMMENT ON TABLE events_bc IS 'SYNTHETIC parity fixture - generated by parity/fixture/gen, never extracted';
COMMENT ON TABLE links_bc IS 'SYNTHETIC parity fixture - generated by parity/fixture/gen, never extracted';
COMMENT ON TABLE subjects IS 'SYNTHETIC parity fixture - generated by parity/fixture/gen, never extracted';
COMMENT ON TABLE mv_subject_hierarchy IS 'SYNTHETIC parity fixture - generated by parity/fixture/gen, never extracted';
COMMENT ON TABLE master_mill IS 'SYNTHETIC parity fixture - generated by parity/fixture/gen, never extracted';
